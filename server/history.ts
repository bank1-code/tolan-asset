export function parseHistoryData(value: any): any {
  if (typeof value === "string") { try { return JSON.parse(value); } catch { return null; } }
  return value;
}

// Always insert a new immutable event. This uses the caller's transaction.
type ArchiveEventParams = {
  entityType: "asset" | "custody"; entityId: number; eventType: string;
  sourceKey: string; oldData?: any; newData: any; transferId?: number; exclusionId?: number; inventorySessionId?: number;
};
function archiveRow(ctx: any, params: ArchiveEventParams, now: Date) {
  const snapshot = { version: 1, entityType: params.entityType, entityId: params.entityId, eventType: params.eventType,
    oldData: params.oldData ?? null, newData: params.newData, performedBy: ctx.user.id, performedByName: ctx.user.name,
    recordedAt: now.toISOString() };
  const data = params.newData;
  const label = historyLabels[params.eventType] || params.eventType;
  const name = data.entityName || data.assetName || data.name || data.transferSnapshot?.entityName || `#${params.entityId}`;
  return { entityType: params.entityType, operationType: label,
    assetId: params.entityType === "asset" ? params.entityId : null, custodyId: params.entityType === "custody" ? params.entityId : null,
    transferId: params.transferId ?? null, exclusionId: params.exclusionId ?? null, inventorySessionId: params.inventorySessionId ?? null,
    sourceKey: params.sourceKey, snapshot, documentTitle: `${label}: ${name}`, fileName: `${params.sourceKey.replace(/:/g, "_")}.html`,
    filePath: null, isAutoGenerated: true, createdBy: ctx.user.id, notes: null };
}
export async function archiveEvent(tx: any, ctx: any, params: ArchiveEventParams) {
  await tx.insert(archiveDocuments).values(archiveRow(ctx, params, new Date()));
}
// Bounded bulk writes retain one immutable document per entity in the caller's transaction.
export async function archiveEvents(tx: any, ctx: any, events: ArchiveEventParams[]) {
  const now = new Date();
  let rows: ReturnType<typeof archiveRow>[] = [], bytes = 0;
  const flush = async () => {
    if (rows.length) await tx.insert(archiveDocuments).values(rows);
    rows = []; bytes = 0;
  };
  for (const event of events) {
    const row = archiveRow(ctx, event, now);
    const size = Buffer.byteLength(JSON.stringify(row), "utf8");
    if (rows.length && (rows.length >= 50 || bytes + size > 1_000_000)) await flush();
    rows.push(row); bytes += size;
  }
  await flush();
}

export async function historyAudit(tx: any, ctx: any, params: {
  entityType: "asset" | "custody"; entityId: number; tableName: string; recordId: number; actionType: string;
  oldData?: any; newData: any; actionDescription: string; changedFields?: string[]; transferId?: number; exclusionId?: number;
}) {
  const inserted = await tx.insert(auditLog).values({ tableName: params.tableName, recordId: params.recordId,
    actionType: params.actionType, actionDescription: params.actionDescription, oldData: params.oldData ?? null,
    newData: params.newData, changedFields: params.changedFields ?? null,
    performedBy: ctx.user.id, performedByName: ctx.user.name, ipAddress: ctx.req.ip || null, userAgent: ctx.req.headers["user-agent"] || null });
  await archiveEvent(tx, ctx, { ...params, eventType: params.actionType, sourceKey: `audit:${Number(inserted[0].insertId)}` });
}
