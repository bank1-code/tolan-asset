import { z } from "zod";
import { eq, and, or, like, desc, sql, getTableColumns } from "drizzle-orm";
import { TRPCError } from "@trpc/server";
import { operatorProcedure, adminProcedure, router } from "./_core/trpc";
import { getDb } from "./db";
import { archiveDocuments, auditLog, assets, custodyItems } from "../drizzle/schema";
import { isStoredImageUrl } from "../shared/imageUrls";
import crypto from "node:crypto";

async function database() { const db = await getDb(); if (!db) throw new TRPCError({ code: "INTERNAL_SERVER_ERROR" }); return db; }
const archiveFilters=z.object({entityType:z.string().optional(),search:z.string().max(500).optional()});
const archiveWhere=(input?:z.infer<typeof archiveFilters>)=>and(input?.entityType?eq(archiveDocuments.entityType,input.entityType):undefined,
 input?.search?or(like(archiveDocuments.documentTitle,`%${input.search}%`),like(archiveDocuments.fileName,`%${input.search}%`)):undefined);
const {snapshot: _snapshot, ...archiveMetadata}=getTableColumns(archiveDocuments);
export const archiveRouter = router({
  list: operatorProcedure.input(archiveFilters.extend({limit:z.number().int().min(1).max(200).default(100),offset:z.number().int().min(0).default(0)}).optional()).query(async ({ input }) => {
    const db = await database();
    return db.select(archiveMetadata).from(archiveDocuments).where(archiveWhere(input)).orderBy(desc(archiveDocuments.createdAt),desc(archiveDocuments.id)).limit(input?.limit??100).offset(input?.offset??0);
  }),
  count: operatorProcedure.input(archiveFilters.optional()).query(async({input})=>{
    const db=await database();const [row]=await db.select({total:sql<number>`COUNT(*)`}).from(archiveDocuments).where(archiveWhere(input));return {total:Number(row?.total??0)};
  }),
  getById: operatorProcedure.input(z.object({id:z.number().int().positive()})).query(async({input})=>{
    const db=await database();const [row]=await db.select().from(archiveDocuments).where(eq(archiveDocuments.id,input.id)).limit(1);
    if(!row)throw new TRPCError({code:'NOT_FOUND',message:'الوثيقة غير موجودة'});return row;
  }),
  getByEntity: operatorProcedure.input(z.object({ entityType: z.enum(["asset", "custody"]), entityId: z.number().int().positive() })).query(async ({ input }) => {
    const db = await database();
    const [doc] = await db.select().from(archiveDocuments).where(eq(input.entityType === "asset" ? archiveDocuments.assetId : archiveDocuments.custodyId, input.entityId))
      .orderBy(desc(archiveDocuments.createdAt), desc(archiveDocuments.id)).limit(1);
    return doc || null;
  }),
  create: operatorProcedure.input(z.object({ entityType: z.enum(["asset", "custody", "documentation_asset", "documentation_custody"]),
    operationType: z.string().trim().min(1).max(50), assetId: z.number().int().positive().nullish(), custodyId: z.number().int().positive().nullish(),
    transferId: z.number().int().positive().nullish(), documentTitle: z.string().trim().min(1).max(500), fileName: z.string().trim().min(1).max(255),
    filePath: z.string().refine(isStoredImageUrl, "رابط الملف غير صالح").nullish(), notes: z.string().nullish() })).mutation(async ({ input, ctx }) => {
    const db = await database();
    return db.transaction(async tx => {
      if (input.transferId) throw new TRPCError({ code: "BAD_REQUEST", message: "وثائق النقل تنشأ من حركة النقل نفسها" });
      const assetKind = input.entityType.endsWith("asset");
      if ((assetKind && input.custodyId) || (!assetKind && input.assetId)) throw new TRPCError({ code: "BAD_REQUEST", message: "ربط الوثيقة لا يطابق نوعها" });
      const id = input.assetId || input.custodyId;
      if (id) {
        const table = assetKind ? assets : custodyItems;
        const [entity] = await tx.select().from(table).where(eq(table.id, id)).limit(1).for("update");
        if (!entity) throw new TRPCError({ code: "NOT_FOUND" });
      }
      const snapshot = { version: 1, eventType: "DOCUMENT", newData: input, performedBy: ctx.user.id, performedByName: ctx.user.name, recordedAt: new Date().toISOString() };
      const result = await tx.insert(archiveDocuments).values({ ...input, assetId: input.assetId ?? null, custodyId: input.custodyId ?? null,
        createdBy: ctx.user.id, snapshot, sourceKey: `document:${crypto.randomUUID()}`, isAutoGenerated: false });
      const documentId = Number(result[0].insertId);
      await tx.insert(auditLog).values({ tableName: "archive_documents", recordId: documentId, actionType: "CREATE", actionDescription: `إضافة وثيقة تاريخية: ${input.documentTitle}`,
        newData: input, performedBy: ctx.user.id, performedByName: ctx.user.name, ipAddress: ctx.req.ip ?? null, userAgent: ctx.req.headers["user-agent"] ?? null });
      return { success: true, id: documentId };
    });
  }),
  update: operatorProcedure.input(z.object({ id: z.number(), documentTitle: z.string().optional(), notes: z.string().nullish(), operationType: z.string().optional() })).mutation(() => {
    throw new TRPCError({ code: "FORBIDDEN", message: "الوثيقة تاريخية؛ أضف وثيقة جديدة بدل تعديل السابقة" });
  }),
  delete: adminProcedure.input(z.object({ id: z.number(), reason: z.string().optional() })).mutation(() => {
    throw new TRPCError({ code: "FORBIDDEN", message: "لا يمكن حذف وثيقة تاريخية من الأرشيف" });
  }),
});
