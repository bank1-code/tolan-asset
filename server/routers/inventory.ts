      if (old.assetCode !== (updateData.assetCode || null)) changedFields.push('assetCode');
      if (old.quantity !== updateData.quantity) changedFields.push('quantity');
      if (old.assetValue !== (updateData.assetValue || '0')) changedFields.push('assetValue');
      if (old.condition !== (updateData.condition || null)) changedFields.push('condition');
      if (old.assignedTo !== (updateData.assignedTo || null)) changedFields.push('assignedTo');
