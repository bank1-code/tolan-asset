      if (old.locationId !== (updateData.locationId || null)) changedFields.push('locationId');
      if (old.status !== (updateData.status || old.status)) changedFields.push('status');
      if (old.notes !== (updateData.notes || null)) changedFields.push('notes');

      // أرشفة تلقائية عند تعديل أصل
